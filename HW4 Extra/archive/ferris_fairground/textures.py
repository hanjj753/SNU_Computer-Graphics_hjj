def create_nameplate():
    """Return one 2-column x 4-row atlas of eight 512x160 signs."""
    width,height=1024,640
    tile_width,tile_height=512,160
    data=bytearray(bytes((13,24,30))*(width*height))

    def pixel(x,y,color):
        if 0<=x<width and 0<=y<height:
            offset=(y*width+x)*3
            data[offset:offset+3]=bytes(color)

    def line(y,x0,x1,color):
        for x in range(x0,x1): pixel(x,y,color)

    def text(value,x0,y0,y,scale,color):
        glyphs=[FONT[c] for c in value]
        text_width=sum(len(g[0])+1 for g in glyphs)*scale-scale
        x=x0+(tile_width-text_width)//2
        for glyph in glyphs:
            for row,bits in enumerate(glyph):
                for column,bit in enumerate(bits):
                    if bit=='1':
                        for dy in range(scale):
                            for dx in range(scale):pixel(x+column*scale+dx,y0+y+row*scale+dy,color)
            x+=(len(glyph[0])+1)*scale

    signs=(
        ('NIGHT ORBIT','CORNELL FAIR / 2026'),
        ('TICKETS','ADMIT ONE / 08 SEATS'),
        ('POPCORN','FRESH / HOT / SWEET'),
        ('ENTRANCE','WELCOME TO THE FAIR'),
        ('NIGHT FAIR','LITTLE LIGHTS / BIG NIGHTS'),
        ('NEXT RIDE','EVERY 75 SECONDS'),
        ('EXIT','THANK YOU / COME AGAIN'),
        ('OPEN','ONE MORE RIDE'),
    )
    for index,(title,subtitle) in enumerate(signs):
        x0=(index%2)*tile_width
        y0=(index//2)*tile_height
        for y in (12,13,146,147):line(y+y0,x0+15,x0+497,(132,105,66))
        glyph_width=sum(len(FONT[c][0])+1 for c in title)-1
        scale=min(8,420//glyph_width)
        text(title,x0,y0,28,scale,(244,219,170))
        line(y0+96,x0+56,x0+456,(79,94,93))
        text(subtitle,x0,y0,112,2,(151,191,185))
    return pyglet.image.ImageData(width,height,'RGB',bytes(data),pitch=-width*3).get_texture()
